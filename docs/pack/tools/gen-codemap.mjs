#!/usr/bin/env node
// gen-codemap.mjs
//
// Regenerates docs/pack/59-CODEMAP.md from the working tree. One row per
// first-party file: its path, its size in bytes, and a one-line purpose taken
// from the file itself rather than invented.
//
//   node docs/pack/tools/gen-codemap.mjs            write the file
//   node docs/pack/tools/gen-codemap.mjs --check    exit 1 if it is stale
//   node docs/pack/tools/gen-codemap.mjs --stdout   print, write nothing
//
// Why a script and not a hand-written list: 59-CODEMAP.md is tier "derived".
// A hand edit is reverted by the next run, which is the point. The command in
// its generated_by front matter key is the one above.
//
// Determinism. Everything is sorted, sizes are exact bytes, and nothing reads
// the clock except the header's date, which comes from the git commit rather
// than from now(), so two runs on one commit produce identical bytes.

import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../..')
const OUT = path.join(ROOT, 'docs/pack/59-CODEMAP.md')
const MODE = process.argv.includes('--check') ? 'check'
  : process.argv.includes('--stdout') ? 'stdout' : 'write'

// ---------------------------------------------------------------- first-party
// Tracked files are the definition of first-party. Anything git ignores is
// somebody else's (node_modules) or a build artefact (.next, target).
function tracked () {
  return execFileSync('git', ['ls-files', '-z'], { cwd: ROOT, maxBuffer: 64 << 20 })
    .toString('utf8').split('\0').filter(Boolean).sort()
}

// Build output that happens to be tracked. Each pattern carries its reason so
// that nobody later removes one without knowing what it was doing.
const EXCLUDE = [
  [/\.pdf$/, 'a rendered document, regenerated from its source'],
  [/\.print\.html$/, 'a print intermediate, regenerated'],
  [/^docs\/mvp0\/screens\/.*\.(html|png)$/, 'generated by docs/mvp0/screens/gen.mjs'],
  [/^docs\/mvp0\/screens\/icons\/.*\.svg$/, 'fetched by docs/mvp0/screens/fetch-icons.mjs'],
  [/^package-lock\.json$/, 'a lockfile, not read by a person'],
  [/^public\/decisions\//, 'a copy of decisions/, built'],
  [/\.(ico|woff2?|ttf|otf|jpe?g|gif|webp|avif|mp4|zip|tgz)$/, 'a binary asset'],
]
function excluded (f) {
  for (const [re, why] of EXCLUDE) if (re.test(f)) return why
  return null
}

// ------------------------------------------------------------------- purpose
// The purpose comes out of the file. A path-derived label is the last resort
// and is marked so, because a guess that reads like a fact is the thing this
// whole pack exists to avoid.
// A purpose taken out of a file is quoted, in two senses. It is printed inside
// double quotation marks, because it is somebody else's sentence and not ours.
// And it is kept to 18 words, because that is the length at which the house
// writing gate treats a double-quoted span as a quotation rather than as our
// own prose. Without that, one research file's leading sentence containing a
// marketing phrase blocked the whole generated document.
const MAX = 110
const MAX_WORDS = 18

function clean (s) {
  return s
    .replace(/[–—]/g, ' ')   // the pack carries no em or en dashes, ever
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\|/g, '/')               // a pipe would break the table row
    .replace(/`/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

function trunc (s) {
  s = clean(s).replace(/^["']+|["']+$/g, '')
  let cut = false
  const w = s.split(' ')
  if (w.length > MAX_WORDS) { s = w.slice(0, MAX_WORDS).join(' '); cut = true }
  if (s.length > MAX) { s = s.slice(0, MAX - 4).replace(/[\s,;:]+$/, ''); cut = true }
  s = s.replace(/[\s,;:.]+$/, '')
  return cut ? s + ' ...' : s
}

function firstHeading (text) {
  const lines = text.split('\n')
  let i = 0
  if (lines[0]?.trim() === '---') {            // skip YAML front matter
    i = 1
    while (i < lines.length && lines[i].trim() !== '---') i++
    i++
  }
  for (; i < lines.length && i < 80; i++) {
    const l = lines[i].trim()
    if (!l) continue
    const h = l.match(/^#{1,3}\s+(.*)$/)
    if (h) return h[1].replace(/[*_]/g, '')
    if (l.startsWith('>')) continue
    return l.replace(/^[*_>-]+\s*/, '').replace(/[*_]/g, '')
  }
  return null
}

function firstComment (text) {
  const lines = text.split('\n')
  const out = []
  for (let i = 0; i < Math.min(lines.length, 40); i++) {
    const l = lines[i].trim()
    if (!l) { if (out.length) break; continue }
    if (l.startsWith('#!')) continue
    if (l.startsWith('//')) { out.push(l.replace(/^\/\/+\s?/, '')); continue }
    if (l.startsWith('/*')) { out.push(l.replace(/^\/\*+\s?/, '').replace(/\*\/\s*$/, '')); continue }
    if (l.startsWith('*')) { out.push(l.replace(/^\*+\s?/, '').replace(/\*\/\s*$/, '')); continue }
    break
  }
  const joined = out.join(' ').trim()
  return joined.length > 3 ? joined : null
}

function firstSymbol (text) {
  const m = text.match(/^export\s+(?:default\s+)?(?:async\s+)?(function|class|const|interface|type|enum)\s+([A-Za-z0-9_$]+)/m)
  if (m) return `exports ${m[1]} ${m[2]}`
  const d = text.match(/^export\s+default\s+/m)
  if (d) return 'a default export'
  return null
}

// A folder's role, used only when the file itself says nothing. Ordered, so the
// most specific prefix wins.
const ROLES = [
  ['src/modules/', 'a module, hexagonal layers inside'],
  ['src/app/api/', 'an API route handler'],
  ['src/app/', 'an app route or layout'],
  ['src/shared/', 'shared code, no module owns it'],
  ['src/config/', 'configuration, the only place process.env is read'],
  ['src/container/', 'the composition root'],
  ['src-tauri/', 'the desktop shell'],
  ['specs/harness/', 'a gate the harness runs'],
  ['specs/', 'a specification the harness reads'],
  ['scripts/', 'a repository script'],
  ['test/', 'a test'],
  ['public/', 'a public static asset'],
  ['decisions/', 'the decisions site'],
  ['decisions-founders/', 'the founders decision surface'],
  ['docs/pack/', 'this pack'],
  ['docs/research/', 'a research round, archive'],
  ['docs/mvp0/', 'the current plan and its tools'],
  ['docs/build/', 'the document build'],
  ['docs/', 'a document'],
  ['verify/', 'an audit round, archive'],
]
// Files everybody looks for by name, which carry no comment of their own. These
// are labels, so they are still marked as path-derived in the output.
const NAMES = {
  '.gitignore': 'what git ignores',
  '.nvmrc': 'the node version this repository builds on',
  '.vercelignore': 'what the deploy leaves out',
  '.firebaserc': 'which Firebase project the tooling points at',
  'firebase.json': 'Firebase hosting and emulator configuration',
  'firestore.rules': 'the Firestore security rules, live work in phase A',
  'firestore.indexes.json': 'the Firestore composite indexes',
  'package.json': 'dependencies and the 26 npm scripts',
  'tsconfig.json': 'strict, noUncheckedIndexedAccess and exactOptionalPropertyTypes',
  'next.config.ts': 'the Next.js build configuration',
  'next-env.d.ts': 'the Next.js ambient types, generated',
  'postcss.config.mjs': 'the stylesheet pipeline',
  'vercel.json': 'routes, headers and the ignored build step',
  'vitest.config.ts': 'the test runner configuration',
  'eslint.config.mjs': 'lint rules, including the import-boundary ban',
  'README.md': 'the readme for its directory',
  'LICENSE': 'the licence',
}
function role (f) {
  const base = path.basename(f)
  if (NAMES[base] && f === base) return NAMES[base]
  for (const [p, r] of ROLES) if (f.startsWith(p)) return r
  if (NAMES[base]) return NAMES[base]
  return 'at the repository root'
}

const TEXT = /\.(md|ts|tsx|mts|cts|js|mjs|cjs|jsx|css|scss|rs|toml|json|jsonl|txt|yml|yaml|svg|html|sh|py|rules)$/

function purpose (f, abs) {
  let text = ''
  if (TEXT.test(f)) {
    try { text = fs.readFileSync(abs, 'utf8').slice(0, 8000) } catch { text = '' }
  }
  if (text) {
    if (f.endsWith('.md')) { const h = firstHeading(text); if (h) return [trunc(h), 'file'] }
    else {
      const c = firstComment(text); if (c) return [trunc(c), 'file']
      const s = firstSymbol(text); if (s) return [trunc(s), 'file']
      if (f.endsWith('.json')) {
        try {
          const j = JSON.parse(text)
          if (typeof j.description === 'string' && j.description) return [trunc(j.description), 'file']
          if (typeof j.name === 'string' && j.name) return [trunc(`the ${j.name} manifest`), 'file']
        } catch { /* a partial read will not parse; fall through */ }
      }
      const h = firstHeading(text); if (h && f.endsWith('.html')) return [trunc(h), 'file']
    }
  }
  return [role(f), 'path']
}

// ------------------------------------------------------------------- assemble
const files = tracked()
const kept = []
const dropped = new Map()

for (const f of files) {
  const why = excluded(f)
  if (why) { dropped.set(why, (dropped.get(why) || 0) + 1); continue }
  const abs = path.join(ROOT, f)
  let size = 0
  try { size = fs.statSync(abs).size } catch { continue }
  const [what, src] = purpose(f, abs)
  kept.push({ f, size, what, src })
}

const byDir = new Map()
for (const r of kept) {
  const d = path.dirname(r.f) === '.' ? '(repository root)' : path.dirname(r.f)
  if (!byDir.has(d)) byDir.set(d, [])
  byDir.get(d).push(r)
}
const dirs = [...byDir.keys()].sort((a, b) =>
  a === '(repository root)' ? -1 : b === '(repository root)' ? 1 : a.localeCompare(b))

const commit = execFileSync('git', ['rev-parse', '--short=7', 'HEAD'], { cwd: ROOT }).toString().trim()
const commitDate = execFileSync('git', ['log', '-1', '--format=%cs'], { cwd: ROOT }).toString().trim()
const totalBytes = kept.reduce((a, r) => a + r.size, 0)
const fromFile = kept.filter(r => r.src === 'file').length
const fromPath = kept.length - fromFile

function kb (n) {
  if (n < 1024) return `${n} B`
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`
  return `${(n / 1024 / 1024).toFixed(1)} MB`
}

const L = []
L.push('---')
L.push('id: 59-CODEMAP')
L.push('title: Codemap')
L.push('mode: reference')
L.push('tier: derived')
L.push('status: living')
L.push(`updated: ${commitDate}`)
L.push('owner: sagnik')
L.push('generated_by: node docs/pack/tools/gen-codemap.mjs')
L.push('covers: [files, sizes, purpose]')
L.push('---')
L.push('')
L.push('# 59. Codemap')
L.push('')
L.push('**Generated. Do not hand-edit.** Run the command in `generated_by` and commit the result.')
L.push('A hand edit is reverted by the next run.')
L.push('')
L.push(`**Commit:** \`${commit}\`, dated ${commitDate}.`)
L.push('')
L.push('## 1. What is counted')
L.push('')
L.push('**First-party means tracked by git.** Anything git ignores belongs to somebody else')
L.push('(`node_modules`) or is build output (`.next`, `target`).')
L.push('')
L.push('Measure | Value')
L.push(`Files listed | **${kept.length.toLocaleString('en-GB')}**`)
L.push(`Total size | **${kb(totalBytes)}**`)
L.push(`Directories | ${dirs.length}`)
L.push(`Purpose read from the file itself | ${fromFile.toLocaleString('en-GB')}`)
L.push(`Purpose derived from the path, marked \`~\` | ${fromPath.toLocaleString('en-GB')}`)
L.push('')
L.push('## 2. What is excluded, and why')
L.push('')
L.push('Tracked, and left out because it is regenerated rather than written.')
L.push('')
L.push('Reason | Files')
for (const [why, n] of [...dropped.entries()].sort((a, b) => b[1] - a[1])) {
  L.push(`${why} | ${n.toLocaleString('en-GB')}`)
}
L.push('')
L.push('## 3. How to read a row')
L.push('')
L.push('- **A purpose in quotation marks came out of the file**: a markdown heading, a leading')
L.push('  comment, a first export, or a `description` key. It is the file\'s own sentence, shortened')
L.push('  to 18 words, never rewritten.')
L.push('- **A `~` in front of a purpose means it was derived from the path**, because the file said')
L.push('  nothing about itself. Treat it as a label, never as a description.')
L.push('- Sizes are exact bytes at the commit above, rounded for display over 1 KB.')
L.push('- A trailing `...` means the sentence was cut, not that it trailed off.')
L.push('')
L.push('## 4. The files')
for (const d of dirs) {
  const rows = byDir.get(d).sort((a, b) => a.f.localeCompare(b.f))
  const bytes = rows.reduce((a, r) => a + r.size, 0)
  L.push('')
  L.push(`### \`${d}\``)
  L.push('')
  L.push(`${rows.length} file${rows.length === 1 ? '' : 's'}, ${kb(bytes)}.`)
  L.push('')
  L.push('File | Size | Purpose')
  for (const r of rows) {
    const name = path.basename(r.f)
    const what = r.src === 'path' ? `~ ${r.what.replace(/[.!?]$/, '')}` : `"${r.what}"`
    L.push(`\`${name}\` | ${kb(r.size)} | ${what}.`)
  }
}
L.push('')
L.push('## 5. Limits of this file')
L.push('')
L.push('**What was not assessed.** Nothing here says whether a file is used. A tracked file that')
L.push('nothing imports looks exactly like one every screen depends on.')
L.push('')
L.push('**What could not be verified.** A purpose marked `~` was derived from the path and is a')
L.push('label rather than a description. There are ' + fromPath.toLocaleString('en-GB') + ' of them.')
L.push('')
L.push('**What would falsify it.** A file whose leading comment describes something it no longer')
L.push('does. The generator reads the comment and cannot know it is stale.')
L.push('')

const body = L.join('\n')

if (MODE === 'stdout') { process.stdout.write(body); process.exit(0) }
if (MODE === 'check') {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (cur === body) { console.log(`codemap up to date: ${kept.length} files`); process.exit(0) }
  console.error('codemap is STALE. Run: node docs/pack/tools/gen-codemap.mjs')
  process.exit(1)
}
fs.writeFileSync(OUT, body)
console.log(`wrote ${path.relative(ROOT, OUT)}: ${kept.length} files, ${dirs.length} directories, ${kb(totalBytes)}`)
